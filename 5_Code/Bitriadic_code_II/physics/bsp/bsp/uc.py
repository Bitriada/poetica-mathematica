"""Ultra-Complex (UC) algebra in the BSP reading (BSP paper, sec. 3).

UC is the 4-dimensional real algebra generated by i and tau with

    i^2 = -1,   tau^2 = 0,   i*tau = tau*i,

so every element is z = a + b i + tau c + tau d i with a, b, c, d real.
In the Stefan reading (BSP sec. 3.2):

    a  value      temperature magnitude
    b  phase      reversible dynamics direction
    c  trace      phase-boundary indicator (c != 0  <=>  boundary here)
    d  coupling   latent-heat coupling strength

tau^2 = 0 encodes the sharp interface: the boundary marker exists (tau
!= 0) but has zero thickness (tau^2 = 0), and trace components can never
smear through multiplication (Property 9.3).

NOTE ON PROP. 3.2 (audit finding).  The paper prints

    z*w = (aa'-bb') + (ab'+a'b)i + tau(ac'+a'c) + tau(ad'+a'd+bc'-b'c)i.

Expanding z*w = (a+bi)(a'+b'i) + tau[(a+bi)(c'+d'i) + (c+di)(a'+b'i)]
(the only possible product in the commutative algebra it defines, the
Leibniz rule) gives

    value:  (aa'-bb') + (ab'+a'b)i
    trace:  tau(ac'+a'c-bd'-b'd) + tau(ad'+a'd+bc'+b'c)i.

The printed formula drops the -bd'-b'd contribution to the tau-real
part and has a sign error (-b'c instead of +b'c) in the tau-imaginary
part.  This module implements the CORRECT product (verified by the
test-suite against both the expansion above and the Leibniz rule
val1*val2 + tau*(val1*tr2 + val2*tr1)); `prop32_product` reproduces the
paper's printed formula verbatim so the audit can quantify the
difference.

This module is deliberately small and dependency-free (the solver works
on plain numpy arrays for speed; UC objects are used for state
bookkeeping, the SP projections, and exactness tests).
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

__all__ = ["UC", "TAU", "prop32_product", "phi_ext_1db", "prop32_report"]


@dataclass
class UC:
    """z = a + b i + tau c + tau d i  (single element or arrays)."""

    a: np.ndarray
    b: np.ndarray
    c: np.ndarray
    d: np.ndarray

    @classmethod
    def zeros(cls, n: int) -> "UC":
        z = np.zeros(n)
        return cls(z, z.copy(), z.copy(), z.copy())

    @classmethod
    def from_arrays(cls, a, b=0.0, c=0.0, d=0.0) -> "UC":
        return cls(np.asarray(a, float), np.asarray(b, float),
                   np.asarray(c, float), np.asarray(d, float))

    # ------------------------------------------------------------------
    def __add__(self, o: "UC") -> "UC":
        return UC(self.a + o.a, self.b + o.b, self.c + o.c, self.d + o.d)

    def __neg__(self) -> "UC":
        return UC(-self.a, -self.b, -self.c, -self.d)

    def __sub__(self, o: "UC") -> "UC":
        return self + (-o)

    def __eq__(self, o: object) -> bool:
        if not isinstance(o, UC):
            return NotImplemented
        return bool(np.all(self.a == o.a) and np.all(self.b == o.b)
                    and np.all(self.c == o.c) and np.all(self.d == o.d))

    # ------------------------------------------------------------------
    def value(self):
        """val(z) = a + b i (the classically observable part)."""
        return self.a + 1j * self.b

    def trace(self):
        """tr(z) = c + d i (the boundary / latent layer)."""
        return self.c + 1j * self.d

    def leibniz_product(self, w: "UC") -> "UC":
        """z*w = val z * val w + tau (val z * tr w + val w * tr z).

        With val = a+bi, tr = c+di this expands to

            value: (aa'-bb') + (ab'+a'b) i
            trace: (ac'+a'c-bd'-b'd) + (ad'+a'd+bc'+b'c) i

        which is the unique commutative product generated by i, tau.
        """
        a, b, c, d = self.a, self.b, self.c, self.d
        a2, b2, c2, d2 = w.a, w.b, w.c, w.d
        return UC(
            a * a2 - b * b2,                       # value real
            a * b2 + b * a2,                       # value imag
            a * c2 + a2 * c - b * d2 - b2 * d,     # trace real
            a * d2 + a2 * d + b * c2 + b2 * c,     # trace imag
        )

    __mul__ = leibniz_product

    def tau_squared_check(self) -> float:
        """tau^2 must be exactly 0 (sharp interface encoding)."""
        tau = UC(np.zeros_like(self.a), np.zeros_like(self.a),
                 np.ones_like(self.a), np.zeros_like(self.a))
        sq = tau.leibniz_product(tau)
        return float(np.max(np.abs(np.stack([sq.a, sq.b, sq.c, sq.d]))))


def prop32_product(z: UC, w: UC) -> UC:
    """The multiplication formula EXACTLY as printed in Prop. 3.2 of the
    BSP paper (kept verbatim for the audit; NOT the correct product)."""
    a, b, c, d = z.a, z.b, z.c, z.d
    a2, b2, c2, d2 = w.a, w.b, w.c, w.d
    return UC(
        a * a2 - b * b2,
        a * b2 + b * a2,
        a * c2 + a2 * c,
        a * d2 + a2 * d + b * c2 - b2 * c,
    )


#: the nilpotent generator tau (boundary marker unit)
TAU = UC.from_arrays(0.0, 0.0, 1.0, 0.0)


def phi_ext_1db(z: UC):
    """Extrinsic projection of the 1DB-SP (BSP Def. 5.2):

        phi_ext^(1)(z) = (a, sqrt(b^2 + c^2 + d^2)) : UC -> R^2,

    'temperature magnitude' and 'phase complexity'.  Returns an array
    with columns (X, Y) usable as the first two coordinates of the
    SP-manifold M_SP = R^4 (BSP Def. 6.1).
    """
    return np.stack([z.a, np.sqrt(z.b ** 2 + z.c ** 2 + z.d ** 2)], axis=-1)


def prop32_report(rng: np.random.Generator, n: int = 1000) -> dict:
    """Quantify the Prop. 3.2 deviation from the correct product."""
    z = UC.from_arrays(rng.standard_normal(n), rng.standard_normal(n),
                       rng.standard_normal(n), rng.standard_normal(n))
    w = UC.from_arrays(rng.standard_normal(n), rng.standard_normal(n),
                       rng.standard_normal(n), rng.standard_normal(n))
    correct = z.leibniz_product(w)
    printed = prop32_product(z, w)
    dev = np.stack([printed.c - correct.c, printed.d - correct.d])
    return {
        "n_samples": n,
        "max_tau_real_deviation": float(np.max(np.abs(dev[0]))),
        "max_tau_imag_deviation": float(np.max(np.abs(dev[1]))),
        "value_parts_agree": bool(np.allclose(printed.a, correct.a)
                                  and np.allclose(printed.b, correct.b)),
        "tau_parts_agree": bool(np.allclose(printed.c, correct.c, atol=1e-12)
                                and np.allclose(printed.d, correct.d, atol=1e-12)),
    }
